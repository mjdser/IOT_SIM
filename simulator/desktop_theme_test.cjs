const fs=require('node:fs'),path=require('node:path');
module.exports=async(win,root)=>{
 const js=c=>win.webContents.executeJavaScript(c),wait=ms=>new Promise(r=>setTimeout(r,ms));
 const bright=data=>{const b=Buffer.from(data.frame,'base64'),n=b[0]|b[1]<<8;return ((n>>11)&31)*.2126*255/31+((n>>5)&63)*.7152*255/63+(n&31)*.0722*255/31>128};
 await js("window.benchTest.view('camera')");await wait(300);
 const initial=await js("window.pipelineTest.action({action:'reset'})");
 if(!bright(initial)||initial.build.theme!=='light')throw Error('White theme was not restored');
 const point=await js("window.pipelineTest.point('sw_theme')");
 win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
 win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});await wait(650);
 const dark=await js("window.pipelineTest.action({action:'frame'})");
 if(bright(dark)||dark.tree.widgets.find(w=>w.id==='lbl_theme').text!=='Dark')throw Error('Theme switch only changed its label');
 await js("window.pipelineTest.action({action:'reset'})");
 const id=await js("window.pipelineTest.action({action:'tap_id',id:'sw_theme'})");
 if(JSON.stringify(id.tree)!==JSON.stringify(dark.tree))throw Error('Glass click differs from TAP_ID');
 const light=await js("window.pipelineTest.action({action:'tap_id',id:'sw_theme'})");
 if(!bright(light)||light.tree.widgets.find(w=>w.id==='lbl_theme').text!=='Light')throw Error('Theme switch did not restore white');
 await js("window.pipelineTest.action({action:'tap_id',id:'color_5'})");await wait(400);
 const state=(await js('window.pipelineTest.snapshot()')).tree;
 if(state.widgets.find(w=>w.id==='lbl_current').text!=='Current: Purple')throw Error('Purple selection failed');
 fs.writeFileSync(path.join(root,'test-results/theme-repair.png'),(await win.webContents.capturePage()).toPNG());
 fs.writeFileSync(path.join(root,'test-results/theme-desktop.json'),JSON.stringify({passed:true,whiteInitial:true,actualDarkAndLightPixels:true,mouseMatchesTapId:true,purpleSelection:true},null,2));
};
